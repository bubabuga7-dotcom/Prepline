-- Prepline stage 5: compact answer storage (one row per finished test instead of one row per question).
-- Run once in Supabase → SQL Editor, AFTER stage4.sql.
--
-- Why: answer_log grows by 30 rows per test (~3.5 KB). answer_attempts stores the same test in one
-- row (~0.5 KB with indexes, measured: 200 tests = 106 KB vs 720 KB), so the database grows about 7x slower.
-- Old rows in answer_log are kept and still counted; new tests are written here.
--
--   marks: one character per question, in the order of q_ids:  c = correct, w = wrong, s = skipped

create table if not exists public.answer_attempts (
  id         bigint generated always as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  mock_id    text not null check (char_length(mock_id) between 1 and 60),
  q_ids      int2[] not null,
  marks      text   not null check (marks ~ '^[cws]+$'),
  created_at timestamptz not null default now(),
  check (cardinality(q_ids) between 1 and 200 and char_length(marks) = cardinality(q_ids))
);
create index if not exists answer_attempts_user on public.answer_attempts (user_id, mock_id);

alter table public.answer_attempts enable row level security;
drop policy if exists attempts_read  on public.answer_attempts;
drop policy if exists attempts_write on public.answer_attempts;
create policy attempts_read  on public.answer_attempts for select to authenticated using (user_id = auth.uid());
create policy attempts_write on public.answer_attempts for insert to authenticated with check (user_id = auth.uid());
grant select, insert on public.answer_attempts to authenticated;

