-- topic statistics of the signed-in student: old answer_log rows + new compact rows.
-- Computed in the database, so the dashboard downloads ~40 small rows instead of thousands.
create or replace function public.my_topic_stats()
returns table (topic text, total int, correct int)
language sql stable security definer set search_path = public as $$
  with t as (
    select l.topic, l.correct
    from answer_log l
    where l.user_id = auth.uid() and l.topic is not null
    union all
    select qt.topic, substr(a.marks, x.i::int, 1) = 'c'
    from answer_attempts a
    cross join lateral unnest(a.q_ids) with ordinality as x(q_id, i)
    join question_topics qt on qt.mock_id = a.mock_id and qt.q_id = x.q_id
    where a.user_id = auth.uid()
  )
  select t.topic, count(*)::int, count(*) filter (where t.correct)::int
  from t group by t.topic order by 1;
$$;
revoke all on function public.my_topic_stats() from public, anon;
grant execute on function public.my_topic_stats() to authenticated;

-- explanations (stage 4): a question counts as attempted if it is in either table or a live room
create or replace function public.attempted_question(p_mock text, p_q int)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from answer_attempts a
                 where a.user_id = auth.uid() and a.mock_id = p_mock and p_q = any (a.q_ids))
      or exists (select 1 from answer_log l
                 where l.user_id = auth.uid() and l.mock_id = p_mock and l.q_id = p_q)
      or exists (select 1 from room_answers a join rooms r on r.id = a.room_id
                 where a.user_id = auth.uid() and r.mock_id = p_mock and a.q_id = p_q);
$$;
