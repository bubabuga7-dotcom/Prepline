# -*- coding: utf-8 -*-
"""
Prepline: builds topics-index.js — which questions belong to which topic.
The topic trainer (topics.html) reads it. Run again after tagging new questions:

    python build-topics.py
"""
import glob
import json
import re

SKIP = {"weak-spots.html"}
Q = re.compile(r"^const (?:questions|QUESTIONS)\s*=\s*(\[.*\]);\s*$", re.M)


def main():
    index = {}
    for f in sorted(glob.glob("*.html")):
        if f in SKIP:
            continue
        html = open(f, encoding="utf-8", errors="ignore").read()
        m = Q.search(html)
        if not m:
            continue
        try:
            qs = json.loads(m.group(1))
        except Exception as e:
            print("  skip " + f + ": " + str(e)[:60])
            continue
        mock = f[:-5]
        for q in qs:
            t = q.get("topic")
            if not t or not q.get("options") or q.get("verified") is False or not isinstance(q.get("id"), int):
                continue
            index.setdefault(t, []).append([mock, q["id"]])

    total = sum(len(v) for v in index.values())
    body = json.dumps(index, separators=(",", ":"), sort_keys=True)
    with open("topics-index.js", "w", encoding="utf-8") as fh:
        fh.write("/* Generated by build-topics.py: topic code -> [[test page, question id], ...]. Do not edit by hand. */\n")
        fh.write("window.PREPLINE_TOPIC_INDEX = " + body + ";\n")
    print("topics-index.js: %d topics, %d questions" % (len(index), total))


if __name__ == "__main__":
    main()
